"""Self-healing step for CI.

Layer 1: deterministic fixers (black, ruff --fix): fast, free, no AI.
Layer 2: an LLM reads the failure output and proposes a minimal fix.

Guardrails: max attempts, file allowlist, tests are never edited by the LLM,
secrets are masked before anything is sent, and a human reviews the PR.
"""

import json
import os
import re
import subprocess
from pathlib import Path

from llm import ask

MAX_ATTEMPTS = 2
MAX_FAILURE_CHARS = 6000
MAX_FILE_CHARS = 8000
SECRET_PATTERN = re.compile(
    r"(ghp_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|AKIA[0-9A-Z]{16}"
    r"|(?i:token|secret|password|api[_-]?key)\s*[=:]\s*\S+)"
)

SYSTEM_PROMPT = """You are a CI repair bot for the order-service team.
A CI check failed. Fix it with the SMALLEST possible change.

Rules:
- You may only change files under app/ (python) and requirements.txt.
- Tests under tests/ are the specification. NEVER change them; fix the code.
- For a bad dependency version, choose a version that pip lists as available.
- Follow the team standards and the runbooks below.

TEAM STANDARDS:
{standards}

RUNBOOKS:
{runbooks}

Reply with ONLY a JSON object, no markdown fences:
{{"diagnosis": "one or two sentences", "files": [{{"path": "app/x.py", \
"content": "<the complete new file content>"}}]}}
"""


def run(cmd: str) -> tuple[int, str]:
    proc = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    return proc.returncode, proc.stdout + proc.stderr


def mask(text: str) -> str:
    return SECRET_PATTERN.sub("[masked]", text)


def read_text(path: str) -> str:
    file = Path(path)
    return file.read_text(encoding="utf-8", errors="replace") if file.exists() else ""


def is_allowed(path: str) -> bool:
    file = Path(path)
    if file.is_absolute() or ".." in file.parts:
        return False
    return path == "requirements.txt" or (
        path.startswith("app/") and path.endswith(".py")
    )


def build_context() -> str:
    parts = []
    editable = ["requirements.txt"] + sorted(str(p) for p in Path("app").rglob("*.py"))
    for name in editable:
        parts.append(f"=== {name} (editable) ===\n{read_text(name)[:MAX_FILE_CHARS]}")
    for test in sorted(Path("tests").glob("*.py")):
        parts.append(f"=== {test} (READ ONLY) ===\n{read_text(str(test))[:MAX_FILE_CHARS]}")
    return "\n\n".join(parts)


def build_runbooks() -> str:
    books = sorted(Path("runbooks").glob("*.md"))
    return "\n\n".join(f"## {b.name}\n{read_text(str(b))}" for b in books) or "(none)"


def layer1_then_check() -> tuple[bool, str]:
    """Run the deterministic fixers, then the full checks."""
    run("black app tests")
    run("ruff check --fix app tests")
    code, output = run("bash scripts/check.sh")
    return code == 0, output


def parse_reply(reply: str) -> dict:
    start, end = reply.find("{"), reply.rfind("}")
    if start == -1 or end == -1:
        raise ValueError("no JSON object in the reply")
    return json.loads(reply[start : end + 1])


def apply_fix(reply: str) -> tuple[str, list[str]]:
    data = parse_reply(reply)
    changed = []
    for item in data.get("files", []):
        path, content = item.get("path", ""), item.get("content")
        if not is_allowed(path) or not isinstance(content, str):
            print(f"[heal] refused to touch: {path!r}")
            continue
        Path(path).write_text(content, encoding="utf-8")
        changed.append(path)
    return data.get("diagnosis", "(no diagnosis)"), changed


def write_results(healed: bool, notes: list[str], last_output: str) -> None:
    lines = ["## Automated fix attempt", ""]
    lines.append("**Result:** " + ("all checks pass" if healed else "still failing"))
    lines += ["", "### What happened", ""] + [f"- {note}" for note in notes]
    if not healed:
        tail = mask(last_output)[-MAX_FAILURE_CHARS:]
        lines += ["", "### Last failure output", "", "```", tail, "```"]
    lines += [
        "",
        "---",
        "_Generated by an LLM and verified by the CI checks. Tests were not changed "
        "by the AI. **A human must review before merging.**_",
    ]
    Path("heal_summary.md").write_text("\n".join(lines), encoding="utf-8")
    output_file = os.getenv("GITHUB_OUTPUT")
    if output_file:
        with open(output_file, "a", encoding="utf-8") as handle:
            handle.write(f"healed={'true' if healed else 'false'}\n")


def main() -> None:
    notes: list[str] = []
    run("pip install -q -r requirements-dev.txt")

    healed, output = layer1_then_check()
    if healed:
        notes.append("Layer 1 (black + ruff --fix) fixed it. No AI needed.")

    system = SYSTEM_PROMPT.format(
        standards=read_text("CONTRIBUTING.md") or "(none)",
        runbooks=build_runbooks(),
    )
    attempt = 0
    while not healed and attempt < MAX_ATTEMPTS:
        attempt += 1
        print(f"[heal] attempt {attempt}: asking the LLM")
        prompt = (
            f"Failure output:\n{mask(output)[-MAX_FAILURE_CHARS:]}\n\n"
            f"Project files:\n{build_context()}"
        )
        try:
            diagnosis, changed = apply_fix(ask(system, prompt))
        except Exception as error:
            print(f"[heal] {type(error).__name__}: {error}")
            notes.append(f"Attempt {attempt}: LLM step failed ({type(error).__name__}).")
            continue
        files = ", ".join(changed) or "no files"
        notes.append(f"Attempt {attempt}: {diagnosis} (changed: {files})")
        healed, output = layer1_then_check()

    write_results(healed, notes, output)
    print(Path("heal_summary.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
